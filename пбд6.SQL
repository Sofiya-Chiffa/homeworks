
CREATE TYPE full_name_type AS (
    last_name varchar(100),
    first_name varchar(100),
    middle_name varchar(100)
);

CREATE DOMAIN full_name_valid AS full_name_type
CHECK (
    (VALUE).last_name IS NOT NULL AND length(trim((VALUE).last_name)) > 1
    AND
    (VALUE).first_name IS NOT NULL AND length(trim((VALUE).first_name)) > 1
);

--
-- УРОВЕНЬ 1. НЕЗАВИСИМЫЕ СПРАВОЧНИКИ
--

CREATE TABLE country (
  country_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code varchar(3) NOT NULL UNIQUE CONSTRAINT chk_country_code_length CHECK (length(code) = 2),
  name varchar(100) NOT NULL UNIQUE CONSTRAINT chk_country_name_length CHECK (length(name) > 2)
);


CREATE TABLE position (
  position_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(100) NOT NULL UNIQUE CONSTRAINT chk_position_name_length CHECK (length(name) > 3),
  base_salary numeric(10,2) NOT NULL
);


CREATE TABLE bbc_section (
  bbc_section_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code varchar(20) NOT NULL UNIQUE,
  name varchar(200) NOT NULL UNIQUE CONSTRAINT chk_bbc_section_name_length CHECK (length(name) > 3)
);


CREATE TABLE event_type (
  event_type_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(100) NOT NULL UNIQUE,
  default_duration smallint NOT NULL DEFAULT 60 CONSTRAINT chk_event_type_duration CHECK (default_duration BETWEEN 15 AND 300)
);


CREATE TABLE location (
  location_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  zone varchar(50) NOT NULL,
  bookcase smallint NOT NULL CONSTRAINT chk_location_bookcase CHECK (bookcase BETWEEN 1 AND 999),
  shelf smallint NOT NULL CONSTRAINT chk_location_shelf CHECK (shelf BETWEEN 1 AND 20),
  max_capacity integer NOT NULL DEFAULT 100 CONSTRAINT chk_location_max_capacity CHECK (max_capacity BETWEEN 10 AND 1000)
);

--
-- УРОВЕНЬ 2. ЗАВИСИМЫЕ СПРАВОЧНИКИ
--

CREATE TABLE publisher (
  publisher_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(200) NOT NULL UNIQUE CONSTRAINT chk_publisher_name_length CHECK (length(name) > 2),
  country_id integer NOT NULL
);

--
-- УРОВЕНЬ 3. КЛЮЧЕВЫЕ ОБЪЕКТЫ
--

CREATE TABLE employee (
  employee_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name full_name_valid NOT NULL,
  position_id integer NOT NULL,
  login varchar(50) NOT NULL UNIQUE CONSTRAINT chk_employee_login_length CHECK (length(login) > 4),
  password varchar(255) NOT NULL CONSTRAINT chk_employee_password_length CHECK (length(password ) > 6),
  email varchar(100) NOT NULL UNIQUE,
  hire_date date NOT NULL DEFAULT CURRENT_DATE,
  is_active boolean NOT NULL DEFAULT true
);


CREATE TABLE reader (
  reader_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  library_card_number varchar(20) NOT NULL UNIQUE CONSTRAINT chk_reader_library_card_number_length CHECK (length(library_card_number) >= 8),
  full_name full_name_valid NOT NULL,
  birth_date date NOT NULL,
  gender char(1) NOT NULL,
  address varchar(255) NOT NULL,
  email varchar(100) UNIQUE,
  reg_date date NOT NULL DEFAULT CURRENT_DATE,
  is_active boolean NOT NULL DEFAULT true
);


CREATE TABLE book_item (
  book_item_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title varchar(255) NOT NULL CONSTRAINT chk_book_item_title_length CHECK (length(title) > 1),
  publisher_id integer NOT NULL ,
  publish_year smallint NOT NULL CONSTRAINT chk_book_item_publish_year CHECK (publish_year BETWEEN 1500 AND EXTRACT(YEAR FROM CURRENT_DATE)),
  pages integer NOT NULL CONSTRAINT chk_book_item_pages CHECK (pages BETWEEN 1 AND 5000),
  inventory_number varchar(50) NOT NULL UNIQUE,
  isbn varchar(20),
  bbc_section_id integer NOT NULL,
  status varchar(20) NOT NULL DEFAULT 'В наличии',
  location_id integer NOT NULL
);


CREATE TABLE author (
  author_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name full_name_valid NOT NULL,
  birth_date date NOT NULL CONSTRAINT chk_author_birth_date CHECK (birth_date < CURRENT_DATE),
  death_date date CONSTRAINT chk_author_death_date CHECK (death_date > birth_date),
  country_id integer NOT NULL
);

--
-- УРОВЕНЬ 4. ДОКУМЕНТЫ И РЕГИСТРЫ
--

CREATE TABLE event (
  event_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(100) NOT NULL CONSTRAINT chk_event_name_length CHECK (length(name) > 3),
  event_date timestamp NOT NULL,
  event_type_id integer NOT NULL,
  employee_id integer NOT NULL,
  location varchar(100) NOT NULL,
  description text,
  status varchar(20) NOT NULL DEFAULT 'Планируется'
);


CREATE TABLE checkout (
  checkout_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  checkout_date date NOT NULL DEFAULT CURRENT_DATE CONSTRAINT chk_checkout_date CHECK (checkout_date <= CURRENT_DATE),
  reader_id integer NOT NULL,
  employee_id integer NOT NULL,
  planned_return_date date NOT NULL DEFAULT (CURRENT_DATE + INTERVAL '30 days') CONSTRAINT chk_checkout_planned_return_date CHECK (planned_return_date > checkout_date),
  status varchar(20) NOT NULL DEFAULT 'Активна'
);
COMMENT ON COLUMN checkout.status IS 'Статус выдачи: "Активна" или "Закрыта"';


CREATE TABLE supply (
  supply_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supply_date date NOT NULL DEFAULT CURRENT_DATE CONSTRAINT chk_supply_date CHECK (supply_date <= CURRENT_DATE),
  supplier varchar(200) NOT NULL,
  employee_id integer NOT NULL,
  invoice_number varchar(50) NOT NULL UNIQUE
);


CREATE TABLE write_off (
  write_off_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  write_off_date date NOT NULL DEFAULT CURRENT_DATE CONSTRAINT chk_write_off_date CHECK (write_off_date <= CURRENT_DATE),
  employee_id integer NOT NULL,
  act_number varchar(50) NOT NULL UNIQUE
);
COMMENT ON TABLE write_off IS 'Акт списания ветхих, утерянных или испорченных книг. Содержит номер акта, дату и сотрудника, оформившего списание.';

--
-- УРОВЕНЬ 5. ПРОМЕЖУТОЧНЫЕ ТАБЛИЦЫ (позиции документов и связи M:N)
--

CREATE TABLE checkout_item (
  checkout_id integer NOT NULL,
  book_item_id integer NOT NULL,
  actual_return_date date CONSTRAINT chk_checkout_item_actual_return_date CHECK (actual_return_date <= CURRENT_DATE),
  fine_amount numeric(10,2) CONSTRAINT chk_checkout_item_fine_amount CHECK (fine_amount >= 0),
  PRIMARY KEY (checkout_id, book_item_id)
);
COMMENT ON TABLE checkout_item IS 'Cписок книг, выданных читателю в рамках одного чека, с информацией о возврате и штрафах';

COMMENT ON COLUMN checkout_item.actual_return_date IS 'Дата фактического возврата книги (NULL означает, что книга ещё на руках у читателя)';


CREATE TABLE supply_item (
  supply_id integer NOT NULL,
  book_item_id integer NOT NULL,
  price numeric(10,2) NOT NULL,
  PRIMARY KEY (supply_id, book_item_id)
);


CREATE TABLE write_off_item (
  write_off_id integer NOT NULL,
  book_item_id integer NOT NULL,
  reason text NOT NULL,
  reader_id integer,
  compensation_status varchar(20),
  PRIMARY KEY (write_off_id, book_item_id)
);


CREATE TABLE employee_phone (
  employee_phone_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id integer NOT NULL,
  phone varchar(20) NOT NULL CONSTRAINT chk_employee_phone_length CHECK (length(phone) = 11)
);


CREATE TABLE reader_phone (
  reader_phone_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reader_id integer NOT NULL,
  phone varchar(20) NOT NULL CONSTRAINT chk_reader_phone_length CHECK (length(phone) = 11)
);


CREATE TABLE book_author (
  author_id integer NOT NULL,
  book_item_id integer NOT NULL,
  PRIMARY KEY (author_id, book_item_id)
);

